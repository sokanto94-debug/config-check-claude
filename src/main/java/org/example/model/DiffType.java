package org.example.model;

/**
 * Тип изменения при сравнении конфигурационных параметров.
 */
public enum DiffType {

    /** Элемент присутствует только в правом контуре (добавлен). */
    ADDED,

    /** Элемент присутствует только в левом контуре (удалён). */
    REMOVED,

    /** Элемент присутствует в обоих контурах, но значения различаются. */
    MODIFIED,

    /** Элемент присутствует в обоих контурах с одинаковым значением. */
    SAME
}
